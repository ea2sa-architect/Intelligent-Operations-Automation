import { writeFile, mkdir } from 'fs/promises';
import { resolve } from 'path';
import { dump } from 'js-yaml';

export default class KongGenerator {
  constructor(config, root) {
    this.config = config;
    this.root = root;
  }

  // Declarative config object — also embedded in the k8s Kong ConfigMap
  // (k8s-generator.js), so both stay in lockstep from one source.
  build() {
    const { services, kongDefaults = {} } = this.config;

    const DECK_TAG = 'ioa-governance';
    const defaultRateLimit = kongDefaults.rateLimit;

    return {
      _format_version: '3.0',
      _transform: true,
      services: services.map(svc => {
        const rl = svc.rateLimit || defaultRateLimit;
        const routePlugins = rl
          ? [{ name: 'rate-limiting', tags: [DECK_TAG], config: { minute: rl.minute, policy: rl.policy, limit_by: rl.limitBy } }]
          : [];

        return {
          name: svc.name,
          url: `http://${svc.name}:${svc.port}`,
          tags: [DECK_TAG],
          routes: svc.routes.map(route => ({
            name: `${svc.name}-route`,
            paths: [route.path],
            strip_path: route.stripPath ?? true,
            methods: route.methods,
            tags: [DECK_TAG],
            ...(routePlugins.length ? { plugins: routePlugins } : {}),
          })),
        };
      }),
    };
  }

  async generate() {
    const kongDir = resolve(this.root, 'kong');
    await mkdir(kongDir, { recursive: true });
    const kongConfig = this.build();

    const content = '# Generated by bootstrap-platform — do not edit manually\n'
      + dump(kongConfig, { lineWidth: 120 });

    await writeFile(resolve(kongDir, 'kong.yaml'), content, 'utf8');
  }
}
