import { writeFile, mkdir, readFile, rm } from 'fs/promises';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { dump } from 'js-yaml';
import KongGenerator from './kong-generator.js';

const __dirname = dirname(fileURLToPath(import.meta.url));

const HEADER = '# Generated by bootstrap-platform — do not edit manually\n';
const PART_OF = 'ioa-governance';

// Apply order matters (scripts/k8s/up.sh applies these stage dirs in sequence):
//   00-base     namespace + network policies
//   10-data     postgres (StatefulSet) + redis
//   20-migrate  schema migration Job (re-created each deploy; Jobs are immutable)
//   30-services one dir per service
//   40-gateway  Kong (DB-less) + NodePort
//   50-ops      backup CronJob
const STAGES = ['00-base', '10-data', '20-migrate', '30-services', '40-gateway', '50-ops'];

// Restricted-profile container hardening, shared by every workload.
const containerSecurity = (extra = {}) => ({
  allowPrivilegeEscalation: false,
  capabilities: { drop: ['ALL'] },
  ...extra,
});
const podSecurity = (uid, extra = {}) => ({
  runAsNonRoot: true,
  runAsUser: uid,
  runAsGroup: uid,
  seccompProfile: { type: 'RuntimeDefault' },
  ...extra,
});

// Keep serving for a few seconds after SIGTERM so the pod is removed from Service
// endpoints before it stops accepting connections (otherwise rolling updates and
// pod replacement drop requests). Native sleep action: needs k8s >= 1.30.
const drainHook = { preStop: { sleep: { seconds: 8 } } };

const secretRef = (secretName, key, optional) => ({
  secretKeyRef: { name: secretName, key, ...(optional ? { optional: true } : {}) },
});

export default class K8sGenerator {
  constructor(config, root) {
    this.config = config;
    this.root = root;
    this.k = config.kubernetes;
    this.ns = config.namespace;
    this.k8sDir = resolve(root, 'k8s');
  }

  async write(relPath, obj) {
    const filePath = resolve(this.k8sDir, relPath);
    await mkdir(dirname(filePath), { recursive: true });
    await writeFile(filePath, HEADER + dump(obj, { lineWidth: 120, noRefs: true }), 'utf8');
  }

  meta(name, tier, extraLabels = {}) {
    return {
      name,
      namespace: this.ns,
      labels: { app: name, tier, 'app.kubernetes.io/part-of': PART_OF, ...extraLabels },
    };
  }

  image(name) { return `${this.config.registry}/${name}:${this.k.imageTag}`; }

  // `${VAR}` values in globalEnv/extraEnv become Secret references; anything
  // else is a literal. (Whole-value only — same convention compose uses.)
  envEntry(name, value) {
    const m = /^\$\{(\w+)\}$/.exec(String(value));
    if (!m) return { name, value: String(value) };
    return { name, valueFrom: secretRef(this.k.secretName, m[1], this.k.optionalSecrets?.includes(m[1])) };
  }

  dbUrl() {
    const { database: db } = this.config;
    // $(POSTGRES_PASSWORD) is expanded by k8s from the env entry that precedes it.
    return `postgresql://${db.user}:$(POSTGRES_PASSWORD)@db:5432/${db.name}`;
  }

  buildDeployment(service) {
    const { globalEnv = {} } = this.config;
    const env = [
      { name: 'NODE_ENV', value: 'production' },
      { name: 'PORT', value: String(service.port) },
      { name: 'POSTGRES_PASSWORD', valueFrom: secretRef(this.k.secretName, 'POSTGRES_PASSWORD') },
      { name: 'DATABASE_URL', value: this.dbUrl() },
      { name: 'DB_SCHEMA', value: service.schema },
      ...Object.entries({ ...globalEnv, ...(service.extraEnv || {}) }).map(([n, v]) => this.envEntry(n, v)),
    ];

    const res = service.resources
      ? { requests: { cpu: service.resources.cpu, memory: service.resources.memory }, limits: { cpu: service.resources.cpu, memory: service.resources.memory } }
      : this.k.defaultResources;
    const probe = (extra) => ({ httpGet: { path: '/health', port: service.port }, ...extra });
    const replicas = service.replicas ?? 1;

    return {
      apiVersion: 'apps/v1',
      kind: 'Deployment',
      metadata: this.meta(service.name, 'app'),
      spec: {
        replicas,
        revisionHistoryLimit: 3,
        strategy: { type: 'RollingUpdate', rollingUpdate: { maxUnavailable: 0, maxSurge: 1 } },
        selector: { matchLabels: { app: service.name } },
        template: {
          metadata: { labels: { app: service.name, tier: 'app', 'app.kubernetes.io/part-of': PART_OF } },
          spec: {
            automountServiceAccountToken: false,
            securityContext: podSecurity(1000),
            terminationGracePeriodSeconds: 30,
            ...(replicas > 1 ? {
              affinity: { podAntiAffinity: { preferredDuringSchedulingIgnoredDuringExecution: [{
                weight: 100,
                podAffinityTerm: { topologyKey: 'kubernetes.io/hostname', labelSelector: { matchLabels: { app: service.name } } },
              }] } },
            } : {}),
            containers: [{
              name: service.name,
              image: this.image(service.name),
              imagePullPolicy: this.k.imagePullPolicy,
              ports: [{ name: 'http', containerPort: service.port }],
              env,
              resources: res,
              securityContext: containerSecurity({ readOnlyRootFilesystem: true }),
              lifecycle: drainHook,
              volumeMounts: [{ name: 'tmp', mountPath: '/tmp' }],
              startupProbe: probe({ periodSeconds: 5, failureThreshold: 24 }),
              readinessProbe: probe({ periodSeconds: 10, timeoutSeconds: 3 }),
              livenessProbe: probe({ periodSeconds: 20, timeoutSeconds: 3, failureThreshold: 3 }),
            }],
            volumes: [{ name: 'tmp', emptyDir: { sizeLimit: '64Mi' } }],
          },
        },
      },
    };
  }

  buildService(service) {
    return {
      apiVersion: 'v1',
      kind: 'Service',
      metadata: this.meta(service.name, 'app'),
      spec: {
        selector: { app: service.name },
        ports: [{ name: 'http', protocol: 'TCP', port: service.port, targetPort: service.port }],
        type: 'ClusterIP',
      },
    };
  }

  buildPdb(service) {
    return {
      apiVersion: 'policy/v1',
      kind: 'PodDisruptionBudget',
      metadata: this.meta(service.name, 'app'),
      spec: { minAvailable: 1, selector: { matchLabels: { app: service.name } } },
    };
  }

  buildNamespace() {
    return {
      apiVersion: 'v1',
      kind: 'Namespace',
      metadata: {
        name: this.ns,
        labels: {
          'managed-by': 'ioa-bootstrap',
          // Every workload below satisfies the restricted profile.
          'pod-security.kubernetes.io/enforce': 'restricted',
          'pod-security.kubernetes.io/warn': 'restricted',
        },
      },
    };
  }

  netpol(name, spec) {
    return {
      apiVersion: 'networking.k8s.io/v1',
      kind: 'NetworkPolicy',
      metadata: { name, namespace: this.ns, labels: { 'app.kubernetes.io/part-of': PART_OF } },
      spec,
    };
  }

  buildNetworkPolicies() {
    const from = (labels) => [{ podSelector: { matchLabels: labels } }];
    return [
      this.netpol('default-deny-ingress', { podSelector: {}, policyTypes: ['Ingress'] }),
      this.netpol('app-from-gateway-and-apps', {
        podSelector: { matchLabels: { tier: 'app' } },
        policyTypes: ['Ingress'],
        ingress: [{ from: [...from({ tier: 'gateway' }), ...from({ tier: 'app' })] }],
      }),
      this.netpol('db-from-apps-and-jobs', {
        podSelector: { matchLabels: { app: 'db' } },
        policyTypes: ['Ingress'],
        ingress: [{ from: [...from({ tier: 'app' }), ...from({ tier: 'job' })], ports: [{ protocol: 'TCP', port: 5432 }] }],
      }),
      this.netpol('redis-from-apps', {
        podSelector: { matchLabels: { app: 'redis-master' } },
        policyTypes: ['Ingress'],
        ingress: [{ from: from({ tier: 'app' }), ports: [{ protocol: 'TCP', port: 6379 }] }],
      }),
      this.netpol('gateway-proxy-open-admin-restricted', {
        podSelector: { matchLabels: { app: 'kong-gateway' } },
        policyTypes: ['Ingress'],
        ingress: [
          { ports: [{ protocol: 'TCP', port: 8000 }] },                                   // proxy: from anywhere (NodePort)
          { from: from({ app: 'mcp-governance-service' }), ports: [{ protocol: 'TCP', port: 8001 }] }, // admin API: provisioner only
        ],
      }),
    ];
  }

  buildPostgres() {
    const { database: db } = this.config;
    const d = this.k.database;
    const pg = (extra) => ({ exec: { command: ['pg_isready', '-h', '127.0.0.1', '-U', db.user, '-d', db.name] }, ...extra });
    return [
      {
        apiVersion: 'v1',
        kind: 'Service',
        metadata: this.meta('db', 'data'),
        spec: { selector: { app: 'db' }, ports: [{ name: 'postgres', port: 5432, targetPort: 5432 }], type: 'ClusterIP' },
      },
      {
        apiVersion: 'apps/v1',
        kind: 'StatefulSet',
        metadata: this.meta('db', 'data'),
        spec: {
          serviceName: 'db',
          replicas: 1,
          selector: { matchLabels: { app: 'db' } },
          template: {
            metadata: { labels: { app: 'db', tier: 'data', 'app.kubernetes.io/part-of': PART_OF } },
            spec: {
              automountServiceAccountToken: false,
              // 70 = the postgres user in the alpine-based timescaledb image.
              securityContext: podSecurity(70, { fsGroup: 70 }),
              terminationGracePeriodSeconds: 60,
              containers: [{
                name: 'db',
                image: d.image,
                imagePullPolicy: this.k.imagePullPolicy,
                ports: [{ name: 'postgres', containerPort: 5432 }],
                env: [
                  { name: 'POSTGRES_DB', value: db.name },
                  { name: 'POSTGRES_USER', value: db.user },
                  { name: 'POSTGRES_PASSWORD', valueFrom: secretRef(this.k.secretName, 'POSTGRES_PASSWORD') },
                  { name: 'PGDATA', value: '/var/lib/postgresql/data/pgdata' },
                  { name: 'TS_TUNE_MEMORY', value: d.tune.memory },
                  { name: 'TS_TUNE_NUM_CPUS', value: String(d.tune.cpus) },
                ],
                resources: { requests: d.requests, limits: d.limits },
                securityContext: containerSecurity(),
                volumeMounts: [
                  { name: 'data', mountPath: '/var/lib/postgresql/data' },
                  { name: 'run', mountPath: '/var/run/postgresql' },
                  { name: 'tmp', mountPath: '/tmp' },
                ],
                startupProbe: pg({ periodSeconds: 5, failureThreshold: 60 }),
                readinessProbe: pg({ periodSeconds: 10, timeoutSeconds: 5 }),
                livenessProbe: pg({ periodSeconds: 20, timeoutSeconds: 5, failureThreshold: 6 }),
              }],
              volumes: [{ name: 'run', emptyDir: {} }, { name: 'tmp', emptyDir: {} }],
            },
          },
          volumeClaimTemplates: [{
            metadata: { name: 'data' },
            spec: { accessModes: ['ReadWriteOnce'], resources: { requests: { storage: d.storage } } },
          }],
        },
      },
    ];
  }

  buildRedis() {
    return [
      {
        apiVersion: 'v1',
        kind: 'Service',
        metadata: this.meta('redis-master', 'data'),
        spec: { selector: { app: 'redis-master' }, ports: [{ name: 'redis', port: 6379, targetPort: 6379 }], type: 'ClusterIP' },
      },
      {
        apiVersion: 'apps/v1',
        kind: 'Deployment',
        metadata: this.meta('redis-master', 'data'),
        spec: {
          replicas: 1,
          selector: { matchLabels: { app: 'redis-master' } },
          template: {
            metadata: { labels: { app: 'redis-master', tier: 'data', 'app.kubernetes.io/part-of': PART_OF } },
            spec: {
              automountServiceAccountToken: false,
              securityContext: podSecurity(999),
              containers: [{
                name: 'redis',
                image: this.k.redis.image,
                imagePullPolicy: this.k.imagePullPolicy,
                // Cache/coordination only — no persistence by design.
                args: ['--save', '', '--appendonly', 'no'],
                ports: [{ name: 'redis', containerPort: 6379 }],
                resources: { requests: { cpu: '50m', memory: '64Mi' }, limits: { cpu: '200m', memory: '128Mi' } },
                securityContext: containerSecurity({ readOnlyRootFilesystem: true }),
                volumeMounts: [{ name: 'data', mountPath: '/data' }],
                readinessProbe: { exec: { command: ['redis-cli', 'ping'] }, periodSeconds: 10 },
                livenessProbe: { exec: { command: ['redis-cli', 'ping'] }, periodSeconds: 20 },
              }],
              volumes: [{ name: 'data', emptyDir: { sizeLimit: '64Mi' } }],
            },
          },
        },
      },
    ];
  }

  buildMigrateJob() {
    return {
      apiVersion: 'batch/v1',
      kind: 'Job',
      metadata: this.meta('ioa-migrate', 'job'),
      spec: {
        backoffLimit: 3,
        ttlSecondsAfterFinished: 86400,
        template: {
          metadata: { labels: { app: 'ioa-migrate', tier: 'job', 'app.kubernetes.io/part-of': PART_OF } },
          spec: {
            restartPolicy: 'OnFailure',
            automountServiceAccountToken: false,
            securityContext: podSecurity(1000),
            containers: [{
              name: 'migrate',
              image: `${this.k.migrate.image}:${this.k.imageTag}`,
              imagePullPolicy: this.k.imagePullPolicy,
              env: [
                { name: 'POSTGRES_PASSWORD', valueFrom: secretRef(this.k.secretName, 'POSTGRES_PASSWORD') },
                { name: 'DATABASE_URL', value: this.dbUrl() },
              ],
              resources: { requests: { cpu: '50m', memory: '64Mi' }, limits: { cpu: '250m', memory: '256Mi' } },
              securityContext: containerSecurity({ readOnlyRootFilesystem: true }),
            }],
          },
        },
      },
    };
  }

  async buildKong() {
    const g = this.k.gateway;
    const pluginDir = resolve(this.root, 'kong-plugins/ioa-mcp-enforcement');
    const plugin = {
      'handler.lua': await readFile(resolve(pluginDir, 'handler.lua'), 'utf8'),
      'schema.lua': await readFile(resolve(pluginDir, 'schema.lua'), 'utf8'),
    };
    const kongYaml = dump(new KongGenerator(this.config, this.root).build(), { lineWidth: 120 });
    const probe = (extra) => ({ httpGet: { path: '/status/ready', port: 8100 }, ...extra });
    const cm = (name, data) => ({
      apiVersion: 'v1', kind: 'ConfigMap', metadata: this.meta(name, 'gateway'), data,
    });

    return [
      cm('kong-declarative-config', { 'kong.yml': kongYaml }),
      cm('kong-plugin-ioa-mcp-enforcement', plugin),
      {
        apiVersion: 'apps/v1',
        kind: 'Deployment',
        metadata: this.meta('kong-gateway', 'gateway'),
        spec: {
          replicas: 2,
          strategy: { type: 'RollingUpdate', rollingUpdate: { maxUnavailable: 0, maxSurge: 1 } },
          selector: { matchLabels: { app: 'kong-gateway' } },
          template: {
            metadata: { labels: { app: 'kong-gateway', tier: 'gateway', 'app.kubernetes.io/part-of': PART_OF } },
            spec: {
              automountServiceAccountToken: false,
              securityContext: podSecurity(1000),
              affinity: { podAntiAffinity: { preferredDuringSchedulingIgnoredDuringExecution: [{
                weight: 100,
                podAffinityTerm: { topologyKey: 'kubernetes.io/hostname', labelSelector: { matchLabels: { app: 'kong-gateway' } } },
              }] } },
              containers: [{
                name: 'kong',
                image: g.image,
                imagePullPolicy: this.k.imagePullPolicy,
                env: [
                  { name: 'KONG_DATABASE', value: 'off' },
                  { name: 'KONG_DECLARATIVE_CONFIG', value: '/etc/kong/kong.yml' },
                  { name: 'KONG_PREFIX', value: '/kong_prefix' },
                  // Default is one worker per host core (16 on Phoenix), which blows the memory limit.
                  { name: 'KONG_NGINX_WORKER_PROCESSES', value: '2' },
                  // Real client IP from the trusted front proxy only. The trusted CIDRs are environment-specific and
                  // kept out of git: they come from the (untracked-source) local ConfigMap; absent => XFF ignored.
                  ...(g.realIp ? [
                    { name: 'KONG_TRUSTED_IPS', valueFrom: { configMapKeyRef: { name: this.k.localConfigMap, key: 'KONG_TRUSTED_IPS', optional: true } } },
                    { name: 'KONG_REAL_IP_HEADER', value: 'X-Forwarded-For' },
                    { name: 'KONG_REAL_IP_RECURSIVE', value: 'on' },
                  ] : []),
                  { name: 'KONG_PROXY_LISTEN', value: '0.0.0.0:8000' },
                  { name: 'KONG_ADMIN_LISTEN', value: '0.0.0.0:8001' },
                  { name: 'KONG_STATUS_LISTEN', value: '0.0.0.0:8100' },
                  { name: 'KONG_PROXY_ACCESS_LOG', value: '/dev/stdout' },
                  { name: 'KONG_ADMIN_ACCESS_LOG', value: '/dev/stdout' },
                  { name: 'KONG_PROXY_ERROR_LOG', value: '/dev/stderr' },
                  { name: 'KONG_ADMIN_ERROR_LOG', value: '/dev/stderr' },
                ],
                ports: [{ name: 'proxy', containerPort: 8000 }, { name: 'admin', containerPort: 8001 }, { name: 'status', containerPort: 8100 }],
                resources: { requests: { cpu: '100m', memory: '256Mi' }, limits: { cpu: '500m', memory: '512Mi' } },
                securityContext: containerSecurity({ readOnlyRootFilesystem: true }),
                lifecycle: drainHook,
                volumeMounts: [
                  { name: 'declarative', mountPath: '/etc/kong', readOnly: true },
                  { name: 'plugin', mountPath: '/usr/local/share/lua/5.1/kong/plugins/ioa-mcp-enforcement', readOnly: true },
                  { name: 'prefix', mountPath: '/kong_prefix' },
                  { name: 'tmp', mountPath: '/tmp' },
                ],
                startupProbe: probe({ periodSeconds: 3, failureThreshold: 30 }),
                readinessProbe: probe({ periodSeconds: 10, timeoutSeconds: 3 }),
                livenessProbe: probe({ periodSeconds: 20, timeoutSeconds: 3 }),
              }],
              volumes: [
                { name: 'declarative', configMap: { name: 'kong-declarative-config' } },
                { name: 'plugin', configMap: { name: 'kong-plugin-ioa-mcp-enforcement' } },
                { name: 'prefix', emptyDir: {} },
                { name: 'tmp', emptyDir: {} },
              ],
            },
          },
        },
      },
      {
        apiVersion: 'policy/v1',
        kind: 'PodDisruptionBudget',
        metadata: this.meta('kong-gateway', 'gateway'),
        spec: { minAvailable: 1, selector: { matchLabels: { app: 'kong-gateway' } } },
      },
      {
        // In-cluster name matches compose's KONG_ADMIN_URL (http://kong-gateway:8001).
        apiVersion: 'v1',
        kind: 'Service',
        metadata: this.meta('kong-gateway', 'gateway'),
        spec: {
          selector: { app: 'kong-gateway' },
          ports: [{ name: 'proxy', port: 8000, targetPort: 8000 }, { name: 'admin', port: 8001, targetPort: 8001 }],
          type: 'ClusterIP',
        },
      },
      {
        // The only thing exposed outside the cluster: nginx on gilbert -> phoenix:<hostPort> -> here.
        apiVersion: 'v1',
        kind: 'Service',
        metadata: this.meta('kong-proxy', 'gateway'),
        spec: {
          selector: { app: 'kong-gateway' },
          ports: [{ name: 'proxy', port: 8000, targetPort: 8000, nodePort: g.nodePort }],
          type: 'NodePort',
          // Local = no SNAT, so Kong sees the real peer (gilbert) and can trust its X-Forwarded-For.
          externalTrafficPolicy: 'Local',
        },
      },
    ];
  }

  buildBackup() {
    const { database: db } = this.config;
    const b = this.k.backup;
    const script = [
      'set -eu',
      'f="/backups/ioa-$(date -u +%Y%m%dT%H%M%SZ).dump"',
      `pg_dump -Fc -h db -U ${db.user} -d ${db.name} -f "$f.tmp"`,
      'mv "$f.tmp" "$f"',
      `ls -1t /backups/ioa-*.dump | tail -n +${b.keep + 1} | xargs -r rm --`,
      'ls -lh /backups',
    ].join('\n');
    return [
      {
        apiVersion: 'v1',
        kind: 'PersistentVolumeClaim',
        metadata: this.meta('ioa-backups', 'data'),
        spec: { accessModes: ['ReadWriteOnce'], resources: { requests: { storage: b.storage } } },
      },
      {
        apiVersion: 'batch/v1',
        kind: 'CronJob',
        metadata: this.meta('ioa-backup', 'job'),
        spec: {
          schedule: b.schedule,
          concurrencyPolicy: 'Forbid',
          startingDeadlineSeconds: 3600,
          successfulJobsHistoryLimit: 3,
          failedJobsHistoryLimit: 3,
          jobTemplate: { spec: {
            backoffLimit: 2,
            template: {
              metadata: { labels: { app: 'ioa-backup', tier: 'job', 'app.kubernetes.io/part-of': PART_OF } },
              spec: {
                restartPolicy: 'OnFailure',
                automountServiceAccountToken: false,
                securityContext: podSecurity(70, { fsGroup: 70 }),
                containers: [{
                  name: 'pg-dump',
                  image: this.k.database.image,
                  imagePullPolicy: this.k.imagePullPolicy,
                  command: ['sh', '-c', script],
                  env: [{ name: 'PGPASSWORD', valueFrom: secretRef(this.k.secretName, 'POSTGRES_PASSWORD') }],
                  resources: { requests: { cpu: '50m', memory: '128Mi' }, limits: { cpu: '500m', memory: '512Mi' } },
                  securityContext: containerSecurity({ readOnlyRootFilesystem: true }),
                  volumeMounts: [{ name: 'backups', mountPath: '/backups' }, { name: 'tmp', mountPath: '/tmp' }],
                }],
                volumes: [
                  { name: 'backups', persistentVolumeClaim: { claimName: 'ioa-backups' } },
                  { name: 'tmp', emptyDir: {} },
                ],
              },
            },
          } },
        },
      },
    ];
  }

  async generate() {
    const { services } = this.config;

    // Regenerate from scratch so removed services/stages don't leave stale files behind.
    await rm(this.k8sDir, { recursive: true, force: true });

    await this.write('00-base/namespace.yaml', this.buildNamespace());
    for (const np of this.buildNetworkPolicies()) await this.write(`00-base/netpol-${np.metadata.name}.yaml`, np);

    const [dbSvc, dbSts] = this.buildPostgres();
    await this.write('10-data/db-service.yaml', dbSvc);
    await this.write('10-data/db-statefulset.yaml', dbSts);
    const [redisSvc, redisDep] = this.buildRedis();
    await this.write('10-data/redis-service.yaml', redisSvc);
    await this.write('10-data/redis-deployment.yaml', redisDep);

    await this.write('20-migrate/migrate-job.yaml', this.buildMigrateJob());

    for (const service of services) {
      const dir = `30-services/${service.name}`;
      await this.write(`${dir}/deployment.yaml`, this.buildDeployment(service));
      await this.write(`${dir}/service.yaml`, this.buildService(service));
      if ((service.replicas ?? 1) > 1) await this.write(`${dir}/pdb.yaml`, this.buildPdb(service));
    }

    const [cmDecl, cmPlugin, kongDep, kongPdb, kongSvc, kongProxy] = await this.buildKong();
    await this.write('40-gateway/kong-declarative-config.yaml', cmDecl);
    await this.write('40-gateway/kong-plugin-configmap.yaml', cmPlugin);
    await this.write('40-gateway/kong-deployment.yaml', kongDep);
    await this.write('40-gateway/kong-pdb.yaml', kongPdb);
    await this.write('40-gateway/kong-service.yaml', kongSvc);
    await this.write('40-gateway/kong-proxy-nodeport.yaml', kongProxy);

    const [bkPvc, bkCron] = this.buildBackup();
    await this.write('50-ops/backup-pvc.yaml', bkPvc);
    await this.write('50-ops/backup-cronjob.yaml', bkCron);
  }
}

export { STAGES };
