import { writeFile } from 'fs/promises';
import { resolve } from 'path';
import { dump } from 'js-yaml';

export default class ComposeGenerator {
  constructor(config, root) {
    this.config = config;
    this.root = root;
  }

  async generate() {
    const { services, database: db, globalEnv } = this.config;
    // EP-310-S6 — sensitive values come from .env; no hardcoded fallback for
    // POSTGRES_PASSWORD so a missing .env value fails loudly at compose up
    // rather than silently running with a weak default credential.
    const dbUrl = `postgresql://\${POSTGRES_USER:-${db.user}}:\${POSTGRES_PASSWORD}@db:5432/\${POSTGRES_DB:-${db.name}}`;

    const composeServices = {};

    // TimescaleDB / Postgres
    composeServices['db'] = {
      image: db.image,
      environment: {
        POSTGRES_DB: `\${POSTGRES_DB:-${db.name}}`,
        POSTGRES_USER: `\${POSTGRES_USER:-${db.user}}`,
        POSTGRES_PASSWORD: '${POSTGRES_PASSWORD}',
      },
      ports: [`${db.port}:5432`],
      volumes: ['ioa-db-data:/var/lib/postgresql/data'],
      networks: ['ioa-network'],
      healthcheck: {
        test: ['CMD-SHELL', `pg_isready -U ${db.user} -d ${db.name}`],
        interval: '10s',
        timeout: '5s',
        retries: 5,
        start_period: '20s',
      },
      restart: 'unless-stopped',
    };

    // App services
    const extraExternalNetworks = new Set();

    for (const svc of services) {
      const networks = ['ioa-network', 'kong-net', ...(svc.extraNetworks || [])];
      for (const n of svc.extraNetworks || []) extraExternalNetworks.add(n);

      composeServices[svc.name] = {
        build: {
          context: `./services/${svc.name}`,
          dockerfile: 'Dockerfile',
        },
        ports: [`${svc.port}:${svc.port}`],
        environment: {
          NODE_ENV: 'development',
          PORT: String(svc.port),
          DATABASE_URL: dbUrl,
          DB_SCHEMA: svc.schema,
          // globalEnv (e.g. AUTH_JWT_PUBLIC_KEY) applies to every service —
          // avoids repeating the same line per service and risking one
          // getting missed when a platform-wide value like a JWT
          // verification key needs to reach all of them.
          ...(globalEnv || {}),
          ...(svc.extraEnv || {}),
        },
        depends_on: { db: { condition: 'service_healthy' } },
        networks,
        restart: 'unless-stopped',
      };
    }

    // Kong is shared infrastructure — not managed here.
    // Services join kong-net so the existing kong-gateway container can reach them.

    const networkDefs = {
      'ioa-network': { driver: 'bridge' },
      'kong-net': { external: true },
    };
    for (const n of extraExternalNetworks) networkDefs[n] = { external: true };

    const compose = {
      services: composeServices,
      networks: networkDefs,
      volumes: { 'ioa-db-data': {} },
    };

    const content = '# Generated by bootstrap-platform — do not edit manually\n'
      + '# yaml-language-server: $schema=https://raw.githubusercontent.com/compose-spec/compose-spec/master/schema/compose-spec.json\n'
      + dump(compose, { lineWidth: 120 });

    await writeFile(resolve(this.root, 'docker-compose.yml'), content, 'utf8');
  }
}
